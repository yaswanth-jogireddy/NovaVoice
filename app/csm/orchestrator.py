"""CSM orchestrator: one caller turn in, a plan for the spoken reply out (HLD section 5).

    guardrails.inbound -> deterministic fast paths (refusals, human request, identity, OTP)
    -> router.route (LLM tool calls, rules fallback) -> policy.decide per proposal
    -> executor (CoreBankingPort) -> TurnPlan(facts + instructions, or a fixed script)

The reply itself is still generated by the session's existing streaming path; this module only
decides what is true and what may be said. Security-relevant steps never depend on the model.
"""
