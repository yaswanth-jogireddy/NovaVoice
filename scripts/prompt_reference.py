OUT = ROOT / "docs" / "PROMPT_AND_TOOLS.md"


def system_prompt(language: str = "en") -> str:
    """The static system message of a call (switchable language), as DemoSession._static_system builds it."""
    stub = SimpleNamespace(_persona_prompt=persona.system_prompt(persona.NAME, "female"), language=language,
                           settings=SimpleNamespace(caller_language_switch=True, demo_expand_contractions=False))
    stub._language_lock = lambda: demo_session.DemoSession._language_lock(stub)
    return demo_session.DemoSession._static_system(stub)


def tool_section() -> list[str]:
    answers = persona.tool_answers()
    out = []
    for spec in TOOLS.values():
        params = spec.parameters.get("properties", {})
        required = set(spec.parameters.get("required", []))
        out += [f"### {spec.name}", "", spec.description, "",
                f"- Permission: **{spec.permission}**" + (" (hidden: run by code, never offered to the model)" if spec.hidden else ""),
                f"- Feature flag: {spec.feature}",
                f"- Side effects: {spec.side_effects}; idempotent: {'yes' if spec.idempotent else 'no'}",
                f"- Failure codes: {', '.join(spec.failure_codes)}"]
        if params:
            out.append("- Arguments:")
            for name, rule in params.items():
                kind = "one of " + ", ".join(rule["enum"]) if "enum" in rule else rule.get("type", "string")
                note = f": {rule['description']}" if rule.get("description") else ""
                out.append(f"  - `{name}` ({kind}{', required' if name in required else ''}){note}")
        else:
            out.append("- Arguments: none")
        guide = answers.get(spec.name)
        if guide:
            out.append(f"- How to answer (prompt.md, Tool answers): {guide}")
        elif spec.name in INSTRUCT:
            out.append(f"- How to answer (code default): {INSTRUCT[spec.name]}")
        out.append("")
    return out


def fixed_lines() -> list[str]:
    out = ["| Key | English | Hindi |", "|---|---|---|"]
    en, hi = persona.LINES["en"], persona.LINES["hi"]
    for key in en:
        out.append(f"| `{key}` | {en[key]} | {hi.get(key, '(English)')} |")
    return out


